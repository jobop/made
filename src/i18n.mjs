export function translateKnownMessage(message, locale = 'zh-CN') {
  if (locale !== 'en' || typeof message !== 'string' || !message) return message;
  if (messages.has(message)) return messages.get(message);
  for (const [pattern, render] of templates) {
    const match = pattern.exec(message);
    if (match) return render(...match);
  }
  return message;
}
export function localizeStatus(value, locale) {
  return { ...value, ...(typeof value?.error === 'string' ? { error: translateKnownMessage(value.error, locale) } : {}) };
}
